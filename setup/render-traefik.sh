#!/usr/bin/env bash
# Trainer only: renders the Traefik chart into plain manifests, so participants install
# Traefik with kubectl before they have learned Helm. Rerun after changing the chart
# version or traefik-values.yaml, and commit traefik.yaml.
set -euo pipefail
cd "$(dirname "$0")"
CHART_VERSION=41.6.1

helm repo add traefik https://traefik.github.io/charts >/dev/null 2>&1 || true
helm repo update traefik >/dev/null

out=traefik.yaml
{
  echo "# Traefik, rendered from the traefik/traefik Helm chart $CHART_VERSION with traefik-values.yaml."
  echo "# Generated by setup/render-traefik.sh. Do not edit by hand."
  echo "apiVersion: v1"
  echo "kind: Namespace"
  echo "metadata:"
  echo "  name: traefik"
  helm template traefik traefik/traefik --version "$CHART_VERSION" \
    -n traefik -f traefik-values.yaml
} > "$out"
echo "wrote setup/$out"
